const form=document.getElementById("prediction-form");
const button=document.getElementById("predict-button");
const message=document.getElementById("form-message");
const resultCard=document.getElementById("result-card");
form.addEventListener("submit",async(event)=>{
 event.preventDefault();message.textContent="";
 const payload=Object.fromEntries(new FormData(form).entries());
 button.disabled=true;button.firstChild.textContent=" Calculating...";
 try{
  const response=await fetch("/api/predict",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(payload)});
  const result=await response.json();
  if(!response.ok)throw new Error(result.error||"Unable to generate prediction.");
  resultCard.innerHTML=`<div class="result-icon">✓</div><p class="eyebrow">YOUR ESTIMATE</p><h2>Estimated property value</h2><div class="result-price">${Number(result.predicted_price).toLocaleString("en-IN",{maximumFractionDigits:2})}</div><p class="result-unit">Price in the same unit as your training dataset</p><div class="result-divider"></div><p class="result-foot">✦ Generated by your trained Linear Regression model</p>`;
 }catch(error){message.textContent=error.message;}
 finally{button.disabled=false;button.firstChild.textContent="Predict house price ";}
});
